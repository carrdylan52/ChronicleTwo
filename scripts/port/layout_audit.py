import collections
import json
import multiprocessing
import os
import re
import shlex
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from inventory_annotate import DEBUG_UNITS, MENU_UNITS  # noqa: E402

ci = None
ASSERT = re.compile(r"^\s*STATIC_ASSERT\(sizeof\((.+)\)\s*==\s*([^)]+)\);")
ASSERT_DIRS = ("ps2/include", "ps2/include/sce", "ps2/include/std", "ps2/src")
ALLOCATORS = {"Alloc", "stAlloc", "stAlloc64", "stAllocTest"}
BYTE_POINTERS = {"char*", "unsignedchar*", "signedchar*", "constchar*", "constunsignedchar*"}
BLOCK = 16
MARKER = "<!-- Generated by scripts/port/layout_audit.py below this line. -->"
HAND = ("kind", "fix", "state", "note")
POINTER_KINDS = None


def load_libclang():
    global ci, POINTER_KINDS
    import clang.cindex as cindex

    ci = cindex
    for candidate in sorted(__import__("glob").glob("/usr/lib/llvm-*/lib/libclang-*.so.*"), reverse=True):
        try:
            ci.Config.set_library_file(candidate)
            ci.Index.create()
            break
        except Exception:
            ci.Config.loaded = False
    POINTER_KINDS = {ci.TypeKind.POINTER, ci.TypeKind.LVALUEREFERENCE, ci.TypeKind.RVALUEREFERENCE,
                     ci.TypeKind.MEMBERPOINTER, ci.TypeKind.BLOCKPOINTER}


def rel(path):
    path = os.path.realpath(path)
    return path[len(ROOT) + 1:] if path.startswith(ROOT + os.sep) else path


def ours(cursor):
    location = cursor.location
    return location.file is not None and rel(location.file.name).startswith(("ps2/src/", "ps2/include/"))


def qualified(cursor):
    parts = []
    while cursor is not None and cursor.kind != ci.CursorKind.TRANSLATION_UNIT:
        if cursor.spelling:
            parts.append(cursor.spelling)
        cursor = cursor.semantic_parent
    return "::".join(reversed(parts))


def spelled_type(t):
    return re.sub(r"\s+", "", t.get_canonical().spelling)


def carries(t, seen):
    """Why a type is not laid out as on the PS2: pointers, vtable pointers, or plain long (LLP64)."""
    declared = re.sub(r"\b(const|volatile)\b", "", t.spelling).strip()
    if declared in ("long", "unsigned long", "long int", "unsigned long int", "signed long"):
        return ["long"]
    t = t.get_canonical()
    if t.kind in POINTER_KINDS:
        return ["pointer"]
    if t.kind in (ci.TypeKind.CONSTANTARRAY, ci.TypeKind.INCOMPLETEARRAY):
        return carries(t.element_type, seen)
    if t.kind != ci.TypeKind.RECORD:
        return []
    key = t.spelling
    if key in seen:
        return seen[key]
    seen[key] = []
    found = []
    declaration = t.get_declaration()
    for child in declaration.get_children():
        if child.kind == ci.CursorKind.CXX_BASE_SPECIFIER:
            found += carries(child.type, seen)
        elif child.kind in (ci.CursorKind.CXX_METHOD, ci.CursorKind.DESTRUCTOR) and child.is_virtual_method():
            found.append("vptr")
    for field in t.get_fields():
        found += ["%s:%s" % (field.spelling or "union", why.split(":")[-1]) for why in carries(field.type, seen)]
    seen[key] = sorted(set(found))
    return seen[key]


def literal(cursor):
    """The value of an integer literal or enumerator, looking through implicit conversions."""
    while cursor.kind in (ci.CursorKind.UNEXPOSED_EXPR, ci.CursorKind.PAREN_EXPR):
        children = list(cursor.get_children())
        if len(children) != 1:
            return None
        cursor = children[0]
    if cursor.kind == ci.CursorKind.DECL_REF_EXPR and cursor.referenced is not None and \
            cursor.referenced.kind == ci.CursorKind.ENUM_CONSTANT_DECL:
        return cursor.referenced.enum_value
    if cursor.kind != ci.CursorKind.INTEGER_LITERAL:
        return None
    tokens = [t.spelling for t in cursor.get_tokens()]
    try:
        return int(tokens[0].rstrip("uUlL"), 0) if tokens else None
    except ValueError:
        return None


def allocation(cursor, depth=0):
    """(call text, blocks) of a mgCMemory allocation with a literal size at or just below cursor."""
    if cursor.kind == ci.CursorKind.CALL_EXPR and cursor.spelling in ALLOCATORS:
        arguments = list(cursor.get_arguments())
        if len(arguments) == 1:
            blocks = literal(arguments[0])
            if blocks is not None:
                return cursor, blocks
        return None
    if depth >= 4:
        return None
    for child in cursor.get_children():
        found = allocation(child, depth + 1)
        if found:
            return found
    return None


def underlying(cursor):
    while cursor.kind in (ci.CursorKind.UNEXPOSED_EXPR, ci.CursorKind.PAREN_EXPR):
        children = list(cursor.get_children())
        if len(children) != 1:
            break
        cursor = children[0]
    return cursor


def element(t):
    """(name, host size) of what a pointer type points at, for records and pointers."""
    t = t.get_canonical()
    if t.kind != ci.TypeKind.POINTER:
        return None
    pointee = t.get_pointee().get_canonical()
    if pointee.kind == ci.TypeKind.RECORD:
        return spelled_type(pointee), pointee.get_size()
    if pointee.kind in POINTER_KINDS:
        return "pointer", pointee.get_size()
    return None


FUNCTION_KINDS = None


def work(item):
    unit, path, args, probes, scratch = item
    load_libclang()
    function_kinds = {ci.CursorKind.FUNCTION_DECL, ci.CursorKind.CXX_METHOD, ci.CursorKind.CONSTRUCTOR,
                      ci.CursorKind.DESTRUCTOR, ci.CursorKind.CONVERSION_FUNCTION, ci.CursorKind.FUNCTION_TEMPLATE}
    probe_path = os.path.join(scratch, unit)
    with open(probe_path, "w") as f:
        f.write('#include "%s"\n' % path)
        for header in sorted({p["file"] for p in probes if not p["file"].startswith("ps2/src/")}):
            f.write('#include "%s"\n' % os.path.join(ROOT, header))
        for probe in probes:
            f.write("using PortLayoutProbe_%d = %s;\n" % (probe["id"], probe["type"]))
            f.write("constexpr auto PortLayoutProbeSize_%d = sizeof(PortLayoutProbe_%d);\n" % (probe["id"], probe["id"]))
    tu = ci.Index.create().parse(probe_path, args=args)
    errors = ["%s:%d: %s" % (rel(d.location.file.name) if d.location.file else "?", d.location.line, d.spelling)
              for d in tu.diagnostics if d.severity >= ci.Diagnostic.Error]
    functions = {}
    calls = collections.defaultdict(set)
    uses = collections.defaultdict(set)
    referenced = set()
    hazards = []
    results = {}
    offsets = []
    stack = [(tu.cursor, None, None)]
    while stack:
        cursor, owner, parent = stack.pop()
        kind = cursor.kind
        if kind in function_kinds and cursor.is_definition() and ours(cursor):
            usr = cursor.get_usr()
            extent = cursor.extent
            functions[usr] = {
                "name": qualified(cursor), "file": rel(cursor.location.file.name), "line": cursor.location.line,
                "start": extent.start.line, "end": extent.end.line,
                "virtual": kind == ci.CursorKind.CXX_METHOD and cursor.is_virtual_method() or
                kind == ci.CursorKind.DESTRUCTOR and cursor.is_virtual_method(),
            }
            owner = usr
        elif kind == ci.CursorKind.TYPE_ALIAS_DECL and cursor.spelling.startswith("PortLayoutProbe_"):
            t = cursor.underlying_typedef_type
            canonical = t.get_canonical()
            declaration = canonical.get_declaration()
            results[int(cursor.spelling.rsplit("_", 1)[1])] = {
                "host": canonical.get_size(), "align": canonical.get_align(), "spelled": spelled_type(t),
                "carries": carries(t, {}),
                "decl": "%s:%d" % (rel(declaration.location.file.name), declaration.location.line)
                if declaration.location.file else "",
            }
            continue
        elif kind in (ci.CursorKind.CALL_EXPR, ci.CursorKind.DECL_REF_EXPR, ci.CursorKind.MEMBER_REF_EXPR):
            target = cursor.referenced
            if target is not None and target.kind in function_kinds:
                usr = target.get_usr()
                referenced.add(usr)
                if owner:
                    calls[owner].add(usr)
            elif owner and target is not None and target.kind == ci.CursorKind.FIELD_DECL:
                parent = target.semantic_parent
                if parent is not None and parent.type.kind != ci.TypeKind.INVALID:
                    uses[owner].add(spelled_type(parent.type))
        elif owner and kind == ci.CursorKind.TYPE_REF:
            target = cursor.referenced
            if target is not None and target.type.get_canonical().kind == ci.TypeKind.RECORD:
                uses[owner].add(spelled_type(target.type))
        if owner and kind in (ci.CursorKind.CSTYLE_CAST_EXPR, ci.CursorKind.CXX_NEW_EXPR,
                              ci.CursorKind.CXX_STATIC_CAST_EXPR, ci.CursorKind.CXX_REINTERPRET_CAST_EXPR):
            target = element(cursor.type)
            found = allocation(cursor) if target is not None else None
            if found and ours(cursor):
                call, blocks = found
                count = None
                if kind == ci.CursorKind.CXX_NEW_EXPR and "[" in "".join(t.spelling for t in cursor.get_tokens()):
                    sizes = [literal(c) for c in cursor.get_children() if c != call and c.kind != ci.CursorKind.CALL_EXPR]
                    sizes = [n for n in sizes if n is not None]
                    count = sizes[-1] if sizes else "n"
                if target[0] != "pointer" or isinstance(count, int):
                    hazards.append({
                        "file": rel(cursor.location.file.name), "line": cursor.location.line, "function": owner,
                        "record": target[0], "host": target[1], "blocks": blocks, "count": count,
                        "call": " ".join(t.spelling for t in call.get_tokens()),
                    })
        if owner and parent is not None and kind == ci.CursorKind.CSTYLE_CAST_EXPR and \
                parent.kind in (ci.CursorKind.BINARY_OPERATOR, ci.CursorKind.VAR_DECL,
                                ci.CursorKind.COMPOUND_ASSIGNMENT_OPERATOR) and ours(cursor) and \
                re.sub(r"\s+", "", cursor.type.get_canonical().spelling) in BYTE_POINTERS:
            operand = underlying(list(cursor.get_children())[-1])
            target = element(operand.type)
            if target is not None:
                offsets.append({
                    "file": rel(cursor.location.file.name), "line": cursor.location.line, "function": owner,
                    "record": target[0], "expression": " ".join(t.spelling for t in parent.get_tokens()),
                })
        if owner and kind == ci.CursorKind.CALL_EXPR and cursor.spelling in ("memcpy", "memset", "memmove") and ours(cursor):
            arguments = list(cursor.get_arguments())
            size = literal(arguments[2]) if len(arguments) == 3 else None
            target = element(underlying(arguments[0]).type) if arguments else None
            if size is not None and target is not None and target[0] != "pointer":
                offsets.append({
                    "file": rel(cursor.location.file.name), "line": cursor.location.line, "function": owner,
                    "record": target[0], "expression": " ".join(t.spelling for t in cursor.get_tokens()),
                })
        for child in cursor.get_children():
            stack.append((child, owner, cursor))
    return {"unit": unit, "functions": functions, "calls": {k: sorted(v) for k, v in calls.items()},
            "uses": {k: sorted(v) for k, v in uses.items()}, "referenced": sorted(referenced),
            "hazards": hazards, "offsets": offsets, "probes": results, "errors": errors}


def compile_units(build):
    with open(os.path.join(build, "compile_commands.json")) as f:
        entries = json.load(f)
    units = {}
    copies = os.path.join(os.path.realpath(build), "ps2_src") + os.sep
    for entry in entries:
        path = os.path.realpath(os.path.join(entry["directory"], entry["file"]))
        if not path.startswith(copies):
            continue
        args = shlex.split(entry["command"]) if "command" in entry else list(entry["arguments"])
        out, skip = [], False
        for arg in args[1:]:
            if skip:
                skip = False
            elif arg in ("-o", "-c"):
                skip = True
            elif os.path.realpath(os.path.join(entry["directory"], arg)) != path:
                out.append(arg)
        units[path[len(copies):]] = (os.path.join(ROOT, "ps2", "src", path[len(copies):]), out)
    return units


def scan_asserts():
    rows = []
    for directory in ASSERT_DIRS:
        for name in sorted(os.listdir(os.path.join(ROOT, directory))):
            path = os.path.join(directory, name)
            if not os.path.isfile(os.path.join(ROOT, path)):
                continue
            with open(os.path.join(ROOT, path), encoding="latin-1") as f:
                for number, text in enumerate(f, 1):
                    match = ASSERT.match(text)
                    if match:
                        rows.append({"file": path, "line": number, "type": match[1].strip(), "size": match[2].strip()})
    return rows


def ps2_size(expression):
    try:
        return int(expression, 0)
    except ValueError:
        return {"FONT_TBL_BIN_SIZE": 0x1000}.get(expression)


def host_units(asserts, units):
    """The unit that lays out each assert's record: its own .cpp, else one that includes the header."""
    includers = collections.defaultdict(list)
    for unit in sorted(units):
        with open(os.path.join(ROOT, "ps2/src", unit), encoding="latin-1") as f:
            for header in re.findall(r'^#include\s+"([^"]+)"', f.read(), re.MULTILINE):
                includers[os.path.basename(header)].append(unit)
    for row in asserts:
        base = os.path.basename(row["file"])
        if row["file"].startswith("ps2/src/"):
            row["unit"] = base
        else:
            own = os.path.splitext(base)[0] + ".cpp"
            row["unit"] = own if own in units else (includers.get(base) or ["mainloop.cpp"])[0]


def boot_steps(path):
    steps = []
    with open(path) as f:
        for line in f:
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) != 4 or not cells[0].isdigit():
                continue
            number, call, source, reaches = cells
            depth = call.count("·")
            names = []

            def hold(match):
                names.append(re.sub(r"\([^()]*\)", "", match[1]))
                return "\0%d\0" % (len(names) - 1)

            text = re.sub(r"`([^`]+)`", hold, call)
            chains = []
            for part in text.split(","):
                chain = []
                for piece in part.split("→"):
                    for index in re.findall(r"\0(\d+)\0", piece):
                        for name in names[int(index)].split(","):
                            name = re.sub(r"[^\w:~]", "", name.split("×")[0].strip())
                            if name and name != "static" and not name.isdigit():
                                chain.append(name)
                if chain:
                    chains.append(chain)
            files = re.findall(r"(\w+\.cpp)", source)
            tokens = re.findall(r"\[(\w+):([\w:~]+)\]", reaches)
            steps.append({"step": int(number), "depth": depth, "chains": chains, "files": files, "tokens": tokens})
    for i, step in enumerate(steps):
        step["container"] = i + 1 < len(steps) and steps[i + 1]["depth"] > step["depth"]
    return steps


def resolve(name, functions, files):
    exact = [u for u, f in functions.items() if f["name"] == name]
    if not exact:
        exact = [u for u, f in functions.items() if f["name"].endswith("::" + name)]
    local = [u for u in exact if os.path.basename(functions[u]["file"]) in files]
    chosen = local or exact
    return chosen if len(chosen) <= 4 else []


def first_uses(steps, functions, calls):
    first = {}
    for step in steps:
        number = step["step"]
        roots, leaves = set(), set()
        for chain in step["chains"]:
            for i, name in enumerate(chain):
                found = resolve(name, functions, step["files"])
                (leaves if i == len(chain) - 1 and not step["container"] else roots).update(found)
        for unit, name in step["tokens"]:
            roots.update(u for u in resolve(name, functions, [unit + ".cpp"])
                         if os.path.basename(functions[u]["file"]) == unit + ".cpp")
        for usr in roots:
            first.setdefault(usr, number)
        pending = list(leaves)
        seen = set(pending)
        while pending:
            usr = pending.pop()
            first.setdefault(usr, number)
            for callee in calls.get(usr, ()):
                if callee not in seen and callee in functions:
                    seen.add(callee)
                    pending.append(callee)
    return first


def position(usr, functions, first, referenced):
    if usr in first:
        return "boot:%d" % first[usr]
    function = functions[usr]
    if usr not in referenced and not function["virtual"] and function["name"] != "main":
        return "dead"
    unit = os.path.splitext(os.path.basename(function["file"]))[0]
    if DEBUG_UNITS.match(unit):
        return "debug"
    if MENU_UNITS.match(unit):
        return "menu"
    return "mode"


ORDER = {"dead": 10 ** 6, "debug": 10 ** 5 + 2, "menu": 10 ** 5 + 1, "mode": 10 ** 5}


def rank(value):
    return int(value[5:]) if value.startswith("boot:") else ORDER.get(value, 10 ** 6)


def earliest(usrs, functions, first, referenced):
    best = None
    for usr in usrs:
        value = position(usr, functions, first, referenced)
        if best is None or rank(value) < rank(best[0]):
            best = (value, functions[usr]["name"])
    return best or ("dead", "")


def read_inventory(path):
    rows = {}
    with open(path) as f:
        for line in f:
            if not line.startswith("| ps2/src/"):
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            rows[(cells[0], cells[1].split("(")[0])] = {"position": cells[4], "wp": cells[5], "state": cells[6]}
    return rows


def read_head(path):
    if not os.path.exists(path):
        return ""
    with open(path) as f:
        head = f.read().partition(MARKER)[0]
    return (head.rstrip() + "\n\n") if head.strip() else ""


def read_decisions(path):
    hand = {}
    if os.path.exists(path):
        with open(path) as f:
            columns = f.readline().rstrip("\n").split("\t")
            for line in f:
                row = dict(zip(columns, line.rstrip("\n").split("\t")))
                hand[(row["table"], row["key"])] = {k: row[k] for k in HAND if row.get(k)}
    return hand


def esc(text):
    return str(text).replace("|", "\\|")


def balanced(text, start):
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
    return text[start + 1:]


def scan_marks():
    """The PortPtr32 guards and PortBlocks counts placed in ps2/src."""
    guards, blocks = [], []
    for name in sorted(os.listdir(os.path.join(ROOT, "ps2/src"))):
        path = "ps2/src/" + name
        with open(os.path.join(ROOT, path), encoding="latin-1") as f:
            for number, text in enumerate(f, 1):
                for match in re.finditer(r"PORT_FIX\(PortPtr32\)\(", text):
                    guards.append({"file": path, "line": number, "expr": balanced(text, match.end() - 1).strip()})
                for match in re.finditer(r"PORT_FIX\(PortBlocks<(.+?)>\)\((0x[0-9A-Fa-f]+|\d+)\)", text):
                    record, count = match[1], 1
                    tail = re.match(r"^(.*),\s*(\d+)$", record)
                    if tail:
                        record, count = tail[1].strip(), int(tail[2])
                    blocks.append({"file": path, "line": number, "type": record, "count": count,
                                   "blocks": int(match[2], 0)})
    return guards, blocks


def owner_of(functions, path, line):
    owners = [u for u, f in functions.items() if f["file"] == path and f["start"] <= line <= f["end"]]
    owners.sort(key=lambda u: functions[u]["end"] - functions[u]["start"])
    return owners[0] if owners else None


def write_host_layouts(path, records):
    names = sorted({r["record"] for r in records if r["computed"] != "faithful"})
    lines = ["#pragma once", "", "// Generated by scripts/port/layout_audit.py.", "",
             "#include <string_view>", "", "inline constexpr std::string_view kPortHostLayouts[] = {"]
    lines += ['    "%s",' % name for name in names]
    lines += ["};", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--build", default="port/build/pc")
    parser.add_argument("--truncations", default="port/build/pc/truncations.json")
    parser.add_argument("--trace", default="scripts/port/boot_trace.md")
    parser.add_argument("--inventory", default="docs/port/HARDWARE_INVENTORY.md")
    parser.add_argument("--layouts", default="docs/port/LAYOUTS.md")
    parser.add_argument("--decisions", default="scripts/port/layout_decisions.tsv")
    parser.add_argument("--header", default="port/include/layout_records.h")
    parser.add_argument("--jobs", type=int, default=os.cpu_count() or 1)
    parser.add_argument("--json", help="also dump the analysis")
    options = parser.parse_args()
    build = os.path.join(ROOT, options.build)
    units = compile_units(build)
    asserts = scan_asserts()
    host_units(asserts, units)
    for i, row in enumerate(asserts):
        row["id"] = i
    guards, blocks = scan_marks()
    probes = collections.defaultdict(list)
    for row in asserts:
        probes[row["unit"]].append(row)
    for i, row in enumerate(blocks):
        row["id"] = 100000 + i
        probes[os.path.basename(row["file"])].append(row)
    scratch = os.path.join(build, "layout_probe")
    os.makedirs(scratch, exist_ok=True)
    items = [(unit, path, args, probes.get(unit, []), scratch) for unit, (path, args) in sorted(units.items())]
    with multiprocessing.Pool(options.jobs) as pool:
        results = pool.map(work, items, chunksize=1)

    functions, calls, uses, referenced, hazards, laid = {}, collections.defaultdict(set), {}, set(), [], {}
    offsets = []
    for result in results:
        for error in result["errors"]:
            print("layout_audit.py: %s: %s" % (result["unit"], error), file=sys.stderr)
        for usr, function in result["functions"].items():
            functions.setdefault(usr, function)
        for usr, callees in result["calls"].items():
            calls[usr].update(callees)
        for usr, records in result["uses"].items():
            uses.setdefault(usr, set()).update(records)
        referenced.update(result["referenced"])
        laid.update(result["probes"])
        hazards += result["hazards"]
        offsets += result["offsets"]
    users = collections.defaultdict(set)
    for usr, records in uses.items():
        for record in records:
            users[record].add(usr)
    first = first_uses(boot_steps(os.path.join(ROOT, options.trace)), functions, calls)
    inventory = read_inventory(os.path.join(ROOT, options.inventory))
    layouts = os.path.join(ROOT, options.layouts)
    head = read_head(layouts)
    hand = read_decisions(os.path.join(ROOT, options.decisions))
    used = set()

    def where(path, line):
        usr = owner_of(functions, path, line)
        return (position(usr, functions, first, referenced), functions[usr]["name"]) if usr else ("dead", "")

    def merged(table, key, row):
        row["key"] = key
        used.add((table, key))
        for column, value in hand.get((table, key), {}).items():
            row[column] = value
        return row

    def keyed(table, base, seen):
        seen[base] += 1
        return base if seen[base] == 1 else "%s #%d" % (base, seen[base])

    records = []
    for row in asserts:
        probe = laid.get(row["id"], {})
        ps2 = ps2_size(row["size"])
        why = probe.get("carries", ["unresolved"])
        faithful = probe.get("host") == ps2 and not why
        pos, user = earliest(users.get(probe.get("spelled"), ()), functions, first, referenced)
        records.append(merged("Records", "%s %s" % (row["file"], row["type"]), {
            "site": "%s:%d" % (row["file"], row["line"]), "record": row["type"],
            "ps2": "0x%X" % ps2 if ps2 is not None else row["size"],
            "host": "0x%X" % probe["host"] if probe.get("host", -1) >= 0 else "?",
            "carries": ", ".join(why[:4]) + (" +%d" % (len(why) - 4) if len(why) > 4 else ""),
            "first_use": pos, "function": user, "computed": "faithful" if faithful else "host",
            "kind": "faithful" if faithful else "runtime record",
            "fix": "assert active" if faithful else "assert neutralised",
            "state": "n/a", "note": "",
        }))

    with open(os.path.join(ROOT, options.truncations)) as f:
        sites = [s for s in json.load(f) if s["file"].startswith("ps2/")]
    casts = []
    seen = collections.Counter()
    for site in sites:
        pos, _ = where(site["file"], site["line"])
        stub = inventory.get((site["file"], site["function"]))
        if stub and stub["state"] == "stub":
            fix, state = "override [%s:%s] (%s)" % (
                os.path.splitext(os.path.basename(site["file"]))[0], site["function"], stub["wp"]), "guarded-unreached"
        elif pos == "dead":
            fix, state = "-", "n/a"
        else:
            fix, state = "", "open"
        expression = re.sub(r"\s+", " ", site["expression"])
        key = keyed("Casts", "%s %s %s" % (site["file"], site["function"], expression), seen)
        casts.append(merged("Casts", key, {
            "site": "%s:%d" % (site["file"], site["line"]), "function": site["function"],
            "kind": site["class"] + " cast", "expression": "`%s`" % expression, "first_use": pos,
            "fix": fix, "state": state, "note": "",
        }))
    for guard in guards:
        pos, name = where(guard["file"], guard["line"])
        key = keyed("Casts", "%s %s PortPtr32(%s)" % (guard["file"], name, guard["expr"]), seen)
        casts.append(merged("Casts", key, {
            "site": "%s:%d" % (guard["file"], guard["line"]), "function": name, "kind": "cast",
            "expression": "`PortPtr32(%s)`" % guard["expr"], "first_use": pos,
            "fix": "guard", "state": "guarded-unreached", "note": "",
        }))

    allocations = []
    seen = collections.Counter()
    record_ps2 = {}
    for row in asserts:
        probe = laid.get(row["id"], {})
        if probe.get("spelled"):
            record_ps2[probe["spelled"]] = ps2_size(row["size"])
    for hazard in sorted(hazards, key=lambda h: (h["file"], h["line"])):
        count = hazard["count"] if isinstance(hazard["count"], int) else 1
        if hazard["host"] <= 0 or hazard["blocks"] * BLOCK >= hazard["host"] * count:
            continue
        pos, name = where(hazard["file"], hazard["line"])
        key = keyed("Allocations", "%s %s %s" % (hazard["file"], name, hazard["call"]), seen)
        allocations.append(merged("Allocations", key, {
            "site": "%s:%d" % (hazard["file"], hazard["line"]), "function": name, "record": hazard["record"],
            "detail": "`%s`: 0x%X bytes for %s0x%X" % (
                hazard["call"], hazard["blocks"] * BLOCK, "%d × " % count if count > 1 else "", hazard["host"]),
            "kind": "allocation", "first_use": pos, "fix": "", "state": "open", "note": "",
        }))
    for row in blocks:
        pos, name = where(row["file"], row["line"])
        host = laid.get(row["id"], {}).get("host", -1)
        need = (host * row["count"] + BLOCK - 1) // BLOCK + 2 if host > 0 else None
        key = keyed("Allocations", "%s %s PortBlocks<%s>(0x%X)" % (row["file"], name, row["type"], row["blocks"]), seen)
        allocations.append(merged("Allocations", key, {
            "site": "%s:%d" % (row["file"], row["line"]), "function": name, "record": row["type"],
            "detail": "PS2 0x%X blocks; host %s × 0x%X bytes takes 0x%X" % (
                row["blocks"], row["count"], host, max(need, row["blocks"])) if need else "host size unknown",
            "kind": "allocation", "first_use": pos, "fix": "PortBlocks", "state": "repaired", "note": "",
        }))

    host_records = {r["record"].replace(" ", "") for r in records if r["computed"] != "faithful"}
    host_records |= {laid[r["id"]]["spelled"] for r in asserts
                     if laid.get(r["id"], {}).get("spelled") and r["type"].replace(" ", "") in host_records}
    offset_rows = []
    seen = collections.Counter()
    done = set()
    for row in sorted(offsets, key=lambda o: (o["file"], o["line"])):
        if (row["file"], row["line"], row["expression"]) in done:
            continue
        done.add((row["file"], row["line"], row["expression"]))
        if row["record"] != "pointer" and row["record"].replace(" ", "") not in host_records:
            continue
        if re.search(r"\b(sizeof|offsetof)\b", row["expression"]):
            continue
        pos, name = where(row["file"], row["line"])
        expression = re.sub(r"\s+", " ", row["expression"])
        key = keyed("Offsets", "%s %s %s" % (row["file"], name, expression), seen)
        offset_rows.append(merged("Offsets", key, {
            "site": "%s:%d" % (row["file"], row["line"]), "function": name, "record": row["record"],
            "expression": "`%s`" % expression, "kind": "byte offset", "first_use": pos,
            "fix": "", "state": "open", "note": "",
        }))

    out = [head + MARKER, ""]
    tables = (
        ("Records", records, ("site", "record", "kind", "ps2", "host", "carries", "first_use", "function",
                              "fix", "state", "note", "key")),
        ("Casts", casts, ("site", "function", "kind", "expression", "first_use", "fix", "state", "note", "key")),
        ("Allocations", allocations, ("site", "function", "record", "detail", "kind", "first_use", "fix", "state",
                                      "note", "key")),
        ("Offsets", offset_rows, ("site", "function", "record", "expression", "kind", "first_use", "fix", "state",
                                  "note", "key")),
    )
    for title, rows, columns in tables:
        states = collections.Counter(r["state"] for r in rows)
        out += ["## %s" % title, "",
                "%d rows: %s." % (len(rows), ", ".join("%s %d" % (s, n) for s, n in sorted(states.items()))), "",
                "| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
        out += ["| " + " | ".join(esc(row.get(c, "")) for c in columns) + " |" for row in rows]
        out.append("")
    with open(layouts, "w") as f:
        f.write("\n".join(out))
    write_host_layouts(os.path.join(ROOT, options.header), records)
    if options.json:
        with open(os.path.join(ROOT, options.json), "w") as f:
            json.dump({"functions": functions, "first": first, "hazards": hazards,
                       "calls": {k: sorted(v) for k, v in calls.items()},
                       "records": records, "casts": casts, "allocations": allocations, "offsets": offsets},
                      f, indent=1)
    for table, key in sorted(set(hand) - used):
        print("layout_audit.py: decision for no row: %s %s" % (table, key), file=sys.stderr)
    print("%s: %d records, %d casts, %d allocations, %d offsets" % (
        rel(layouts), len(records), len(casts), len(allocations), len(offset_rows)))
    return 0


