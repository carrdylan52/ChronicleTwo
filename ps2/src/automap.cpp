void CAutoMapGen::CreatFixedMap(int info_no) {
    CAutoMapParts *cell;
    int           i;
    AUTOMAP_ROOM_INFO *preset = &room_info[info_no];
    int preset_width;
    int preset_height;
    s16 *table;
    int y;
    int x;

    for (i = 0; i < grid_w * grid_h; i++) {
        cell = &grid[i];
        cell->parts_no = -1;
        cell->attr = 0;
        cell->kind = 0;
        cell->room_no = -1;
        cell->road_link = 0;
        cell->link = 0;
        cell->visible = 0;
        cell->wall = -1;
        cell->parts = 0;
    }
    for (i = 0; i < 8; i++) {
        room[i].unk_0 = 0;
    }
    preset_height = preset->h;
    preset_width = preset->w;
    table = preset->table;
    for (y = 0; y < preset_height; y++) {
        for (x = 0; x < preset_width; x++) {
            s16 parts_no = table[0];
            s16 attr = table[1];
            table += 2;
            if (parts_no != -1) {
                (&grid[y * grid_w])[x].parts_no = parts_no;
                (&grid[y * grid_w])[x].attr = attr;
                (&grid[y * grid_w])[x].kind = PartsInfoData[parts_no].kind;
                (&grid[y * grid_w])[x].link = PartsInfoData[parts_no].link;
                (&grid[y * grid_w])[x].road_link = 0;
                (&grid[y * grid_w])[x].room_no = 0;
            }
        }
    }
    room[0].x = 0;
    room[0].y = 0;
    room[0].w = preset_width;
    room[0].h = preset_height;
}

