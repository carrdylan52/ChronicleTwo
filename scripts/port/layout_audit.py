#!/usr/bin/env python3
"""Write the tables of docs/port/LAYOUTS.md: every STATIC_ASSERT(sizeof) record, pointer cast and
PS2-sized allocation, with the boot-trace position where the game first relies on it.

    tools/kazarov/bin/kazarov shell sh -c '
        python3 tools/kazarov/scripts/port_truncations.py --executable darkchronicle --build port/build/pc \
            --out port/build/pc/truncations.md --json port/build/pc/truncations.json &&
        python3 scripts/port/layout_audit.py'

Reads the port's compile commands (port/build/pc), the truncations JSON, scripts/port/boot_trace.md and
docs/port/HARDWARE_INVENTORY.md. Each record is laid out by clang for the host and compared with the
size the PS2 asserts. first_use is boot:<step> of the first boot-trace step that reaches a function
relying on the row (the step's own functions, and for a step with no deeper steps below it everything
they call), else debug, menu or mode by unit as in the inventory, or dead for a function nothing
references. kind, fix, state and note come from scripts/port/layout_decisions.tsv for a row with the same key,
else from the defaults below; everything above the generated tables is kept as written.
"""

