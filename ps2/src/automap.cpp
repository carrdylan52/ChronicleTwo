void CMiniMapSymbol::SetMapInfo(CMap *map, CAutoMapParts *grid, int grid_w, int grid_h,
                                float cell_w, float cell_d) {
    if (map == 0) {
        return;
    }
    this->map = map;
    this->grid = grid;
    this->grid_w = grid_w;
    this->grid_h = grid_h;
    this->cell_w = cell_w;
    this->cell_d = cell_d;
    parts_table = map->GetPlacPartsTable(&parts_num);
    CMapParts *part = parts_table;
    parts_num = 0;

    while ((part->name[0] == 0) == 0) {
        part++;
        parts_num++;
    }
    texture = mgTexManager.GetTexture("minimap1", -1);
    char *floor_name = BattleAreaScene->map_name;
    if (*floor_name == 0) {
        return;
    }
    info = 0;
    char buffer[0x40];
    strcpy(buffer, floor_name);
    if (strlen(buffer) == 7) {
        buffer[6] = 0;
    }
    for (int i = 0; i < MINIMAP_INFO_COUNT; i++) {
        char *entry_name = MiniMapInfoData[i].name;
        if (entry_name != 0 && strcmp(buffer, entry_name) == 0) {
            info = &MiniMapInfoData[i];
            break;
        }
    }
    if (info == 0) {
        return;
    }
    part = parts_table;
    if (part == 0) {
        return;
    }
    for (int i = 0; i < parts_num; i++) {
        char *parts_name = part->parts_name;
        part->unk_1dc = -1;
        for (int j = 0; PartsInfoData[j].name != 0; j++) {
            if (strcmp(PartsInfoData[j].name, parts_name) == 0) {
                part->unk_1dc = info->tile[j];
            }
        }
        part++;
    }
}

