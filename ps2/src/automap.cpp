void CAutoMapGen::SetRoadLinkMark(int x, int y, int side) {
    int ny;
    int nx;
    nx = x;
    ny = y;
    int mark;

    switch (side) {
        case 1:
            ny++;
            mark = 2;
            break;
        case 2:
            ny--;
            mark = 1;
            break;
        case 4:
            nx--;
            mark = 8;
            break;
        case 8:
            nx++;
            mark = 4;
            break;
    }
    (&grid[y * grid_w])[x].link |= (u8)mark;
    (&grid[y * grid_w])[x].road_link |= (u8)mark;
    (&grid[ny * grid_w])[nx].link |= (u8)side;
    (&grid[ny * grid_w])[nx].road_link |= (u8)side;
}

